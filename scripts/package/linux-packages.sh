#!/usr/bin/env bash
# Builds the .deb and .rpm of a Linux release package with nFPM, from the
# tarball package.sh made (flux-<version>-<target>.tar.gz):
#
#   flux-<version>-<amd64|arm64>.deb  and  flux-<version>-<x86_64|aarch64>.rpm
#
# (named like the other assets: GitHub renames a "~" in an asset's name,
# which a .deb's own version uses for a pre-release), laid out as:
#
#   /usr/bin/flux-server, /usr/bin/flux
#   /usr/libexec/flux/sidecar-slim           (when the tarball has it)
#   /usr/share/flux/web/, /usr/share/flux/install-kind ("deb" or "rpm")
#   /usr/lib/systemd/system/flux.service     (the `flux` account, /var/lib/flux)
#   /usr/lib/sysusers.d/flux.conf
#   /etc/flux/flux.toml                      (a config file: upgrades keep changes)
#   /usr/share/doc/flux/                     (LICENSE, README.md, THIRD_PARTY_LICENSES)
#
# The service and the install scripts are in scripts/package/linux/.
#
# Usage:
#   scripts/package/linux-packages.sh --tarball dist/flux-0.1.0-x86_64-unknown-linux-gnu.tar.gz \
#     [--out DIR] [--nfpm PATH]
#
# A version that isn't semver (a "dev" build) has no packages: the script
# says so and exits 0.
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
tarball="" out="" nfpm="nfpm"
maintainer="James Yong <me@jamesyong42.com>"

die() { echo "linux-packages.sh: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --tarball) tarball=${2:?}; shift 2 ;;
    --out) out=${2:?}; shift 2 ;;
    --nfpm) nfpm=${2:?}; shift 2 ;;
    -h | --help) sed -n '2,25p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done
[ -f "$tarball" ] || die "--tarball: no such file: ${tarball:-<unset>}"
[ -n "$out" ] || out=$(dirname "$tarball")
mkdir -p "$out"

name=$(basename "$tarball")
case "$name" in
  *-x86_64-unknown-linux-gnu.tar.gz) target=x86_64-unknown-linux-gnu arch=amd64 rpm_arch=x86_64 ;;
  *-aarch64-unknown-linux-gnu.tar.gz) target=aarch64-unknown-linux-gnu arch=arm64 rpm_arch=aarch64 ;;
  *) die "$name isn't a Linux package (flux-<version>-<x86_64|aarch64>-unknown-linux-gnu.tar.gz)" ;;
esac
version=${name#flux-}
version=${version%-"$target".tar.gz}
if ! printf '%s\n' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$'; then
  echo "linux-packages.sh: $version isn't a release version; no .deb or .rpm"
  exit 0
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
tar -xzf "$tarball" -C "$work"
stage="$work/flux-$version-$target"
[ -x "$stage/bin/flux-server" ] || die "$name has no bin/flux-server"
[ -d "$stage/share/flux/web" ] || die "$name has no share/flux/web"
printf 'deb\n' > "$work/install-kind.deb"
printf 'rpm\n' > "$work/install-kind.rpm"

# A file nFPM puts in place: src, dst, mode.
entry() {
  printf '  - src: "%s"\n    dst: "%s"\n    file_info:\n      mode: %s\n' "$1" "$2" "$3"
}

{
  cat <<EOF
# Generated by scripts/package/linux-packages.sh.
name: flux
arch: $arch
platform: linux
version: "$version"
version_schema: semver
release: 1
section: video
priority: optional
maintainer: "$maintainer"
vendor: vibecook
homepage: https://github.com/vibecook-dev/flux
license: MIT
description: |-
  Self-hosted media server: browse, play and stream your films and shows
  in the browser, on this network and over Tailscale.
recommends:
  - ffmpeg
contents:
EOF
  entry "$stage/bin/flux-server" /usr/bin/flux-server 0755
  [ -x "$stage/bin/flux" ] && entry "$stage/bin/flux" /usr/bin/flux 0755
  [ -f "$stage/bin/sidecar-slim" ] && entry "$stage/bin/sidecar-slim" /usr/libexec/flux/sidecar-slim 0755
  cat <<EOF
  - src: "$stage/share/flux/web"
    dst: /usr/share/flux/web
    type: tree
  - src: "$work/install-kind.deb"
    dst: /usr/share/flux/install-kind
    packager: deb
    file_info:
      mode: 0644
  - src: "$work/install-kind.rpm"
    dst: /usr/share/flux/install-kind
    packager: rpm
    file_info:
      mode: 0644
  - src: "$here/linux/flux.toml"
    dst: /etc/flux/flux.toml
    type: config|noreplace
    file_info:
      mode: 0644
EOF
  entry "$here/linux/flux.service" /usr/lib/systemd/system/flux.service 0644
  entry "$here/linux/flux.sysusers" /usr/lib/sysusers.d/flux.conf 0644
  for doc in LICENSE README.md THIRD_PARTY_LICENSES; do
    [ -f "$stage/$doc" ] && entry "$stage/$doc" "/usr/share/doc/flux/$doc" 0644
  done
  cat <<EOF
scripts:
  preinstall: "$here/linux/preinstall.sh"
  postinstall: "$here/linux/postinstall.sh"
  preremove: "$here/linux/preremove.sh"
  postremove: "$here/linux/postremove.sh"
EOF
} > "$work/nfpm.yaml"

deb="$out/flux-$version-$arch.deb"
rpm="$out/flux-$version-$rpm_arch.rpm"
"$nfpm" package --config "$work/nfpm.yaml" --packager deb --target "$deb"
"$nfpm" package --config "$work/nfpm.yaml" --packager rpm --target "$rpm"
ls -l "$deb" "$rpm"
