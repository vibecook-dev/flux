#!/usr/bin/env bash
# Prints the Homebrew formula for a release (vibecook-dev/homebrew-tap,
# Formula/flux.rb): the release's macOS and Linux tarballs with their
# SHA-256s from SHA256SUMS. release.yml runs it after publishing a release
# and pushes the result to the tap.
#
# Installed by Homebrew, flux is laid out as a release tarball (bin/,
# share/flux/web, share/flux/install-kind saying "homebrew", the Truffle
# sidecar in libexec/flux), and `brew services start vibecook-dev/tap/flux`
# runs it at login.
#
# Usage: scripts/package/homebrew-formula.sh --version 0.1.0 --sums SHA256SUMS > Formula/flux.rb
set -euo pipefail

version="" sums=""
die() { echo "homebrew-formula.sh: $*" >&2; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --version) version=${2:?}; shift 2 ;;
    --sums) sums=${2:?}; shift 2 ;;
    -h | --help) sed -n '2,13p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done
if [ -z "$version" ] || [ ! -f "$sums" ]; then die "usage: homebrew-formula.sh --version <version> --sums <SHA256SUMS>"; fi

sha() {
  local file="flux-$version-$1.tar.gz" sum
  sum=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ ${#sum} -eq 64 ] || die "no SHA-256 for $file in $sums"
  printf '%s' "$sum"
}
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_intel=$(sha x86_64-unknown-linux-gnu)
base="https://github.com/vibecook-dev/flux/releases/download/v#{version}/flux-#{version}"

cat <<EOF
# Generated by scripts/package/homebrew-formula.sh in vibecook-dev/flux, at
# each release: changes made here are replaced by the next one.
class Flux < Formula
  desc "Self-hosted media server: browse, play and stream your films and shows"
  homepage "https://github.com/vibecook-dev/flux"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_intel"
    end
  end

  depends_on "ffmpeg"

  def install
    bin.install "bin/flux-server"
    bin.install "bin/flux" if File.exist?("bin/flux")
    (libexec/"flux").install "bin/sidecar-slim" if File.exist?("bin/sidecar-slim")
    (share/"flux").install "share/flux/web"
    # How flux updates: \`brew upgrade\`, which its update panel says.
    (share/"flux/install-kind").write "homebrew\n"
    doc.install Dir["README*", "LICENSE*", "THIRD_PARTY_LICENSES*"]
  end

  service do
    run [opt_bin/"flux-server"]
    # Not again after a clean stop (\`brew services stop\`, Ctrl-C).
    keep_alive successful_exit: false
    # Without it, launchd throttles CPU and I/O, and transcoding is real time.
    process_type :interactive
    log_path var/"log/flux.log"
    error_log_path var/"log/flux.log"
    environment_variables PATH: std_service_path_env
  end

  def caveats
    <<~TEXT
      Start flux now and at every login:
        brew services start vibecook-dev/tap/flux
      Then open http://localhost:8096 and set it up.
    TEXT
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/flux-server --version")
  end
end
EOF
