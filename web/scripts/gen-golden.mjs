#!/usr/bin/env node
// Regenerates the golden wire-format samples from flux-core itself:
//   cargo run (scripts/golden-rs) → src/api/__golden__/golden.json
//                                  → src/api/__golden__/golden.check.ts
// golden.check.ts holds every sample as a typed object literal (`satisfies`),
// so `pnpm typecheck` fails if types.ts drifts from the Rust structs (missing
// or extra fields, wrong enum strings); golden.test.ts checks enums, explain
// sentences and plan labels at runtime.
//
//   pnpm golden        # CARGO_TARGET_DIR is honoured; default scripts/golden-rs/target
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'src', 'api', '__golden__');
mkdirSync(outDir, { recursive: true });

const json = execFileSync('cargo', ['run', '-q', '--manifest-path', join(here, 'golden-rs', 'Cargo.toml')], {
  encoding: 'utf8',
  maxBuffer: 16 << 20,
});
const golden = JSON.parse(json);
writeFileSync(join(outDir, 'golden.json'), JSON.stringify(golden, null, 2) + '\n');

const TYPES = {
  ServerInfo: 'ServerInfo',
  CreateLibrary: 'CreateLibrary',
  Library: 'Library',
  PageItemSummary: 'Page<ItemSummary>',
  ItemDetail: 'ItemDetail',
  Home: 'Home',
  PlayRequest: 'PlayRequest',
  PlayResponse: 'PlayResponse',
  ProgressReport: 'ProgressReport',
  SessionDiagnostics: 'SessionDiagnostics',
  Events: 'FluxEvent[]',
  NameGuess: 'NameGuess',
  ItemsParams: 'ItemsParams',
  FolderParams: 'FolderParams',
  FolderPage: 'FolderPage',
  PlanPreview: 'PlanPreview',
  MarkWatched: 'MarkWatched',
  TailnetInfo: 'TailnetInfo',
  TailnetConnect: 'TailnetConnect',
  UpdateInfo: 'UpdateInfo',
  UpdateSettings: 'UpdateSettings',
  // The agent contract (src/api/agent.ts).
  AgentItemDetail: 'AgentItemDetail',
  ChangesListOutput: 'ChangesListOutput',
  Changeset: 'Changeset',
  Decided: 'Decided',
  Lenses: 'Lenses',
  FixOutput: 'FixOutput',
  PlanOutput: 'PlanOutput',
  Collections: 'Collections',
  CollectionItems: 'CollectionItems',
  ErrorBody: 'ErrorBody',
  Manifest: 'Manifest',
};
/** Types that live in src/api/agent.ts rather than types.ts. */
const AGENT = new Set([
  'AgentItemDetail',
  'ChangesListOutput',
  'Changeset',
  'Decided',
  'Lenses',
  'FixOutput',
  'PlanOutput',
  'Collections',
  'CollectionItems',
  'ErrorBody',
  'Manifest',
]);
const lines = [
  '// GENERATED by scripts/gen-golden.mjs from crates/flux-core (do not edit).',
  '// Type-checks real serde output against src/api/types.ts.',
  `import type { ${[...new Set(Object.values(TYPES).map((t) => t.replace(/<.*|\[\]/g, '')))].filter((t) => !AGENT.has(t)).concat(['ItemSummary', 'PlaybackPlan', 'Reason']).filter((v, i, a) => a.indexOf(v) === i).join(', ')} } from '../types';`,
  `import type { ${[...AGENT].join(', ')} } from '../agent';`,
  '',
];
for (const [key, type] of Object.entries(TYPES)) {
  lines.push(`export const golden${key} = ${JSON.stringify(golden.samples[key], null, 2)} satisfies ${type};`, '');
}
lines.push(`export const goldenPlans = ${JSON.stringify(golden.plan_labels.map(([p]) => p), null, 2)} satisfies PlaybackPlan[];`, '');
lines.push(`export const goldenReasons = ${JSON.stringify(golden.reasons.map(([r]) => r), null, 2)} satisfies Reason[];`, '');
writeFileSync(join(outDir, 'golden.check.ts'), lines.join('\n'));
console.log(`wrote ${outDir}/golden.json and golden.check.ts`);
