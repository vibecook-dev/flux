/** "Mark watched" / "Mark unwatched" (a show or season marks every episode). */
function WatchedToggle({ item, onChanged }: { item: ItemSummary; onChanged: () => void }) {
  const [busy, setBusy] = useState(false);
  const watched = isWatched(item);
  const noun = item.kind === 'show' ? ' show' : item.kind === 'season' ? ' season' : '';
  return (
    <button
      type="button"
      className="btn btn-lg"
      aria-pressed={watched}
      disabled={busy}
      onClick={() => {
        setBusy(true);
        api
          .markWatched(item.id, !watched)
          .then(onChanged, () => undefined)
          .finally(() => setBusy(false));
      }}
    >
      <Icon name={watched ? 'restart' : 'check'} />
      {watched ? `Mark${noun} unwatched` : `Mark${noun} watched`}
    </button>
  );
}

export default function Item({ params, query }: RouteProps) {
  const id = Number(params.id);
  const q = useItem(id);
  const detail = q.data;
  const summary: ItemSummary | undefined = detail ?? recallSummary(id);
  useTitle(summary?.title);

  // Seasons render as their show with that season open.
  useEffect(() => {
    if (detail?.kind === 'season' && detail.show_id !== null) navigate(`/item/${detail.show_id}?season=${detail.id}`, { replace: true });
  }, [detail]);

  const art = summary?.backdrop ?? (summary?.kind === 'episode' ? summary.poster : null);
  useEffect(() => setAmbientFromHash(art?.blurhash ?? summary?.poster?.blurhash, true), [art?.blurhash, summary?.poster?.blurhash]);

  const assets = useMemo(() => detail?.assets ?? [], [detail]);
  const [assetId, setAssetId] = useState<number | null>(null);
  const [audio, setAudio] = useState<number | null>(null);
  const [sub, setSub] = useState<number | null>(null);
  const asset = assets.find((a) => a.id === assetId) ?? assets.find((a) => a.available) ?? assets[0];

  const root = useRef<HTMLElement>(null);
  const posterRef = useRef<HTMLDivElement>(null);
  const closing = useRef(false);

  // The poster arrives from where it was in the lens; its place there stays empty
  // until it goes back, like a print lifted off a wall.
  useLayoutEffect(() => {
    // Keyboard and screen readers start on the page itself (Tab goes to Back, then on down).
    root.current?.focus({ preventScroll: true });
    const from = takeOrigin(id);
    const slot = posterRef.current?.firstElementChild as HTMLElement | null;
    const view = activeLens()?.view;
    // A lens that draws on a canvas hides the title itself; a DOM lens has an element to hide.
    const source = view?.hide ? null : (view?.artOf?.(id) ?? null);
    view?.hide?.(id);
    if (source) source.style.visibility = 'hidden';
    if (from && slot) void flyElement(slot, { from }, 620);
    return () => {
      view?.hide?.(null);
      if (source) source.style.visibility = '';
    };
  }, [id]);

  // Closing flies the poster back to its place in the lens, then steps back.
  const close = useCallback(() => {
    if (closing.current) return;
    closing.current = true;
    const leave = () => back('/');
    const slot = posterRef.current?.firstElementChild as HTMLElement | null;
    const to = rectInLens(id);
    if (reducedMotion() || !root.current) return leave();
    root.current.dataset.leaving = '';
    if (slot && to) void flyElement(slot, { to }, 480).then(leave);
    else setTimeout(leave, 240);
  }, [id]);

  // Esc closes with the flight (the shell would close without it).
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key !== 'Escape' || e.defaultPrevented) return;
      const t = e.target as HTMLElement | null;
      if (t?.closest('dialog, [role="menu"], select')) return;
      e.preventDefault();
      close();
    };
    window.addEventListener('keydown', onKey, true);
    return () => window.removeEventListener('keydown', onKey, true);
  }, [close]);

  useEffect(() => {
    closing.current = false;
    root.current?.scrollTo({ top: 0 });
  }, [id]);

  if (!summary) {
    if (q.status === 'error') {
      return (
        <article className={styles.overlay} ref={root} tabIndex={-1}>
          <div className={styles.missing}>
            <h1 className="display-l">This title isn’t available</h1>
            <p className="muted">It may have been removed from the library, or the server isn’t reachable.</p>
            <button type="button" className="btn" onClick={close}>
              Back to the library
            </button>
          </div>
        </article>
      );
    }
    return <article className={styles.overlay} ref={root} tabIndex={-1} aria-busy="true" aria-label="Loading" />;
  }

  const isShow = summary.kind === 'show';
  const isEpisode = summary.kind === 'episode';
  const p = summary.progress;
  const resumable = isResumable(summary);
  const canPlay = isShow || (asset?.available ?? false);
  const meta: string[] = [];
  if (isEpisode && summary.subtitle) meta.push(summary.subtitle);
  if (summary.year && !isEpisode) meta.push(String(summary.year));
  if (isShow && summary.child_count) meta.push(`${summary.child_count} season${summary.child_count === 1 ? '' : 's'}`);
  if (detail?.runtime_ms) meta.push(isShow ? `${Math.round(detail.runtime_ms / 60000)}-min episodes` : formatRuntime(detail.runtime_ms));
  if (detail?.genres.length) meta.push(detail.genres.join(', '));
  const facts = asset ? assetFacts(asset, audio) : summary.badges;
  const play = (fromStart: boolean) =>
    startPlay(id, { assetId: isShow ? null : (asset?.id ?? null), audioTrack: audio, subtitleTrack: sub, startMs: fromStart ? 0 : null });
  const posterLabel = sourceLabel(summary.poster);
  const posterColumn = hasPosterColumn(summary.kind);
  const tint = deepen(paletteOf(summary).c1, 0.07);

  return (
    <article ref={root} className={styles.overlay} style={{ '--tint': tint } as CSSProperties} aria-label={summary.title} tabIndex={-1}>
      <div className={styles.backdrop} aria-hidden="true">
        {art ? (
          <Art art={art} width={1600} aspect="wide" title="" priority showSourceLabel={false} className={styles.backdropArt} />
        ) : (
          <Art art={summary.poster} width={160} aspect="poster" title="" showSourceLabel={false} className={styles.backdropBlur} />
        )}
        <div className={styles.scrim} />
      </div>
      <button type="button" className={`${styles.back} glass glass-btn`} onClick={close} aria-label="Back to the library" title="Back (esc)">
        <Icon name="back" />
      </button>

      <div className={styles.layout} data-poster={posterColumn || undefined} key={`hero-${id}`}>
        {posterColumn && (
          <div className={styles.posterCol}>
            <div ref={posterRef}>
              <Art art={summary.poster} width={360} aspect="poster" title={summary.title} priority className={styles.poster} />
            </div>
            {posterLabel && <p className={styles.posterNote}>{posterLabel.long}</p>}
          </div>
        )}

        <div className={styles.main}>
          {isEpisode && detail?.show_id !== null && detail?.show_id !== undefined && <ShowLink showId={detail.show_id} title={detail.parent_title} />}
          <p className={`edge ${styles.eyebrow}`}>{isShow ? 'Show' : isEpisode ? 'Episode' : summary.kind === 'movie' ? 'Film' : summary.kind}</p>
          <h1 className={`display-xl ${styles.title}`}>{summary.title}</h1>
          <p className={styles.meta}>{meta.join(' · ') || ' '}</p>

          {facts.length > 0 && (
            <ul className={styles.facts} aria-label="Quality">
              {facts.map((f) => (
                <li key={f} className="edge">
                  {f}
                </li>
              ))}
            </ul>
          )}

          {detail?.overview && <p className={styles.overview}>{detail.overview}</p>}
          {!detail && <div className={`skeleton ${styles.overviewSkeleton}`} />}

          <div className={styles.actions}>
            <button type="button" className={`${styles.play} glass glass-tint glass-btn`} disabled={!canPlay && Boolean(detail)} onClick={() => play(false)} onPointerEnter={preloadPlayer} onFocus={preloadPlayer}>
              <Icon name="play" />
              {resumable && p ? `Resume ${formatClock(p.position_ms)}` : isShow ? 'Play next episode' : 'Play'}
            </button>
            {resumable && (
              <button type="button" className="btn btn-lg" onClick={() => play(true)} onPointerEnter={preloadPlayer} onFocus={preloadPlayer} disabled={!canPlay}>
                <Icon name="restart" />
                From the start
              </button>
            )}
            {detail && (
              <WatchedToggle
                item={detail}
                onChanged={() => {
                  // Progress shows on this page, the season list, Home, every library grid and folder.
                  void q.refetch();
                  invalidateQueries('children:');
                  invalidateQueries(keys.home);
                  refreshLibrary();
                  refreshFolders();
                }}
              />
            )}
          </div>

          {!isShow && <ExpectedPlayback itemId={id} asset={asset} audio={audio} sub={sub} />}

          {!isShow && (
            <>
              <VersionPicker
                assets={assets}
                value={asset?.id ?? null}
                onChange={(v) => {
                  setAssetId(v);
                  setAudio(null);
                  setSub(null);
                }}
              />
              <TrackPickers asset={asset} audio={audio} sub={sub} onAudio={setAudio} onSub={setSub} />
            </>
          )}
        </div>
      </div>

      {isShow && <Seasons key={`seasons-${id}`} showId={id} initialSeason={Number(query.get('season')) || null} />}

      {detail && (
        <div className={styles.panels}>
          <MatchPanel item={detail} />
          {!isShow && <FilesPanel assets={assets} />}
        </div>
      )}

      {isEpisode && detail?.show_id !== null && detail?.show_id !== undefined && <MoreEpisodes showId={detail.show_id} seasonNumber={detail.season_number} currentId={id} />}
    </article>
  );
}

function MoreEpisodes({ showId, seasonNumber, currentId }: { showId: number; seasonNumber: number | null; currentId: number }) {
  const seasons = useChildren(showId);
  // flux-catalog names season 0 "Specials"; the mock says "Season 0".
  const season = seasons.data?.find((s) => s.title === `Season ${seasonNumber}` || (seasonNumber === 0 && s.title === 'Specials'));
  const eps = useChildren(season?.id ?? null);
  const list = (eps.data ?? []).filter((e) => e.id !== currentId);
  if (list.length === 0) return null;
  return (
    <section className={styles.more} aria-label={`More from season ${seasonNumber}`}>
      <h2 className="display-m">More from season {seasonNumber}</h2>
      <div className={styles.moreGrid}>
        {list.slice(0, 8).map((e) => (
          <PosterCard key={e.id} item={e} width={260} />
        ))}
      </div>
    </section>
  );
}
