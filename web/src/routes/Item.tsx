/**
 * What this device will get: the server's own planner (`POST /api/v1/plan`, a
 * dry run of Play, ~1 ms), so the page never promises something Play won't do.
 * The client sketch (plan/predict.ts) only fills in if the server can't answer;
 * it disagreed with the server on every MPEG-TS file in the e2e library.
 */
function ExpectedPlayback({ itemId, asset, audio, sub }: { itemId: number; asset: AssetInfo | undefined; audio: number | null; sub: number | null }) {
  const caps = useCaps();
  const ready = Boolean(caps && asset?.available);
  const preview = useQuery<PlanPreview>(
    ready && asset ? `plan:${itemId}:${asset.id}:${audio ?? ''}:${sub ?? ''}` : 'plan:none',
    () => api.plan({ item_id: itemId, asset_id: asset?.id ?? null, caps: caps as NonNullable<typeof caps>, audio_track: audio, subtitle_track: sub, start_ms: null }),
    { enabled: ready, staleMs: 60_000 },
  );
  const sketch = useMemo(
    () => (preview.status === 'error' && caps && asset?.probe ? predictPlan({ probe: asset.probe, caps, audioTrack: audio, subtitleTrack: sub, subtitleFiles: asset.subtitle_files }) : null),
    [preview.status, caps, asset, audio, sub],
  );
  const predicted = preview.data ? { plan: preview.data.plan, explain: preview.data.explain } : sketch;
  if (!asset) return null;
  if (!asset.available) {
    return (
      <p className={styles.expected} data-tone="transcode">
        <span className={styles.expectedDot} aria-hidden="true" />
        <span>
          <strong>Offline</strong> · this file’s drive isn’t responding. flux kept the item and it will play again when the drive is back.
        </span>
      </p>
    );
  }
  if (!predicted) return <p className={`${styles.expected} skeleton`} aria-hidden="true" />;
  const label = planLabel(predicted.plan);
  const why = predicted.explain[0] ?? null;
  const plain: Record<string, string> = {
    'Direct play': 'Plays the original file as-is',
    'Direct stream': 'Repackaged on the fly, no quality loss',
    'Audio conversion': 'Picture untouched; audio converted',
    Transcode: 'Video converted for this device',
  };
  return (
    <p className={styles.expected} data-tone={planTone(label)} title={preview.data ? 'What flux will do for this browser when you press Play' : "Predicted from this browser's capabilities; the server decides when you press Play"}>
      <span className={styles.expectedDot} aria-hidden="true" />
      <span>
        <strong>{label}</strong> · {plain[label]}
        {why && <span className={styles.expectedWhy}>{why}.</span>}
      </span>
    </p>
  );
}

function VersionPicker({ assets, value, onChange }: { assets: AssetInfo[]; value: number | null; onChange: (id: number) => void }) {
  if (assets.length < 2) return null;
  // Two 2160p files must not both read "2160p" (e2e P2 #7).
  const names = versionNames(assets);
  return (
    <fieldset className={styles.versions}>
      <legend className={styles.subhead}>Version</legend>
      <div className={styles.versionList}>
        {assets.map((a, i) => (
          <label key={a.id} className={styles.version} data-offline={!a.available || undefined} title={a.path}>
            <input type="radio" name="version" checked={value === a.id} onChange={() => onChange(a.id)} />
            <span className={styles.versionName}>{names[i]}</span>
            <span className="edge">{[...assetFacts(a), containerName(a.container)].join(' · ')}</span>
            <span className={`edge ${styles.versionSize}`}>
              {formatBytes(a.size)}
              {!a.available && ' · offline'}
            </span>
          </label>
        ))}
      </div>
    </fieldset>
  );
}

function TrackPickers({ asset, audio, sub, onAudio, onSub }: { asset: AssetInfo | undefined; audio: number | null; sub: number | null; onAudio: (i: number | null) => void; onSub: (i: number | null) => void }) {
  const tracks = asset?.probe?.tracks ?? [];
  const audios = tracks.filter((t) => t.kind === 'audio');
  // Tracks of the file, then subtitle files beside it.
  const subs = subtitleChoices(asset);
  if (audios.length < 2 && subs.length === 0) return null;
  const defaultAudio = audios.find((t) => t.default) ?? audios[0];
  return (
    <div className={styles.pickers}>
      {audios.length > 0 && (
        <label className="field">
          <span>Audio</span>
          <select className="select" value={audio ?? defaultAudio?.index ?? ''} onChange={(e) => onAudio(Number(e.target.value))} disabled={audios.length < 2}>
            {audios.map((t) => (
              <option key={t.index} value={t.index}>
                {audioLabel(t)}
              </option>
            ))}
          </select>
        </label>
      )}
      {subs.length > 0 && (
        <label className="field">
          <span>Subtitles</span>
          <select className="select" value={sub ?? ''} onChange={(e) => onSub(e.target.value === '' ? null : Number(e.target.value))}>
            <option value="">Off</option>
            {subs.map((s) => (
              <option key={s.track} value={s.track}>
                {s.burnIn ? `${s.label} · burned in` : s.label}
              </option>
            ))}
          </select>
        </label>
      )}
    </div>
  );
}

function EpisodeRow({ ep }: { ep: ItemSummary }) {
  const p = ep.progress;
  const frac = p && p.duration_ms ? p.position_ms / p.duration_ms : 0;
  return (
    <li className={styles.episode}>
      <Link to={`/item/${ep.id}`} className={styles.episodeLink}>
        <span className={styles.episodeArt}>
          <Art art={ep.poster} width={220} aspect="wide" title={ep.title} />
          {p && !p.watched && (
            <span className={styles.episodeProgress}>
              <span style={{ width: `${frac * 100}%` }} />
            </span>
          )}
        </span>
        <span className={styles.episodeText}>
          <span className="edge">
            {ep.subtitle}
            {p?.watched ? ' · watched' : p ? ` · ${formatRemaining(p.position_ms, p.duration_ms)}` : ''}
          </span>
          <span className={styles.episodeTitle}>{ep.title}</span>
          {ep.badges.length > 0 && <span className="edge">{ep.badges.join(' · ')}</span>}
        </span>
      </Link>
      <button type="button" className={styles.episodePlay} onClick={() => startPlay(ep.id)} onPointerEnter={preloadPlayer} aria-label={`Play ${ep.subtitle ?? ep.title}`}>
        <Icon name="play" />
      </button>
    </li>
  );
}

function Seasons({ showId, initialSeason }: { showId: number; initialSeason: number | null }) {
  const seasons = useChildren(showId);
  const list = seasons.data ?? [];
  const [picked, setPicked] = useState<number | null>(initialSeason);
  const current = list.find((s) => s.id === picked) ?? list.find((s) => s.title !== 'Season 0') ?? list[0];
  const episodes = useChildren(current?.id ?? null);
  useEffect(() => {
    if (episodes.data) rememberSummaries(episodes.data);
  }, [episodes.data]);
  if (!seasons.data) return <div className={`skeleton ${styles.seasonsSkeleton}`} />;
  return (
    <section className={styles.seasons} aria-label="Seasons and episodes">
      <div className={styles.seasonTabs} role="tablist" aria-label="Seasons">
        {list.map((s) => (
          <button key={s.id} type="button" role="tab" aria-selected={s.id === current?.id} className={styles.seasonTab} onClick={() => setPicked(s.id)}>
            {s.title === 'Season 0' ? 'Specials' : s.title}
            <span className="edge">{s.child_count}</span>
          </button>
        ))}
      </div>
      <ol className={styles.episodes} role="tabpanel" aria-label={current?.title}>
        {episodes.data
          ? episodes.data.map((ep) => <EpisodeRow key={ep.id} ep={ep} />)
          : Array.from({ length: 4 }, (_, i) => <li key={i} className={`skeleton ${styles.episodeSkeleton}`} />)}
      </ol>
    </section>
  );
}

