const PROVIDER_LINKS: Record<string, (id: string, kind: string) => string> = {
  tmdb: (id, kind) => `https://www.themoviedb.org/${kind === 'show' ? 'tv' : 'movie'}/${id}`,
  imdb: (id) => `https://www.imdb.com/title/${id}/`,
  tvdb: (id) => `https://thetvdb.com/dereferrer/series/${id}`,
};

const PROVIDER_NAMES: Record<string, string> = { tmdb: 'TMDB', imdb: 'IMDb', tvdb: 'TheTVDB' };

/** "Poster from TMDB" / "Poster: a frame from the video (no AI)" / "Poster: AI-generated on this server". */
function artCredit(kind: string, art: ItemSummary['poster']): string | null {
  if (!art) return null;
  switch (art.source) {
    case 'provider':
      return `${kind} from the metadata provider`;
    case 'local':
      return `${kind} from a file next to the media`;
    case 'frame':
      return `${kind}: a frame from the video, typeset by flux (no AI)`;
    case 'generated':
      return `${kind}: generated by AI on this server`;
  }
}

function Meter({ value }: { value: number }) {
  const pct = Math.round(value * 100);
  const word = value >= 0.9 ? 'High' : value >= 0.6 ? 'Medium' : 'Low';
  return (
    <div className={styles.meter}>
      <span className={styles.meterTrack} role="meter" aria-valuemin={0} aria-valuemax={100} aria-valuenow={pct} aria-label="Match confidence">
        <span className={styles.meterFill} data-level={word.toLowerCase()} style={{ width: `${pct}%` }} />
      </span>
      <span className="edge">
        {pct}% · {word}
      </span>
    </div>
  );
}

function MatchPanel({ item }: { item: ItemDetail }) {
  if (item.match_confidence === null && item.match_evidence.length === 0) return null;
  const aiAssisted = item.match_evidence.some((e) => /\bAI\b/.test(e));
  const credits = [artCredit('Poster', item.poster), artCredit('Backdrop', item.backdrop)].filter(Boolean) as string[];
  const usesTmdb = item.external_ids.some(([p]) => p === 'tmdb');
  return (
    <section className={styles.panel} aria-labelledby="matched-as">
      <h2 id="matched-as" className={`edge ${styles.panelTitle}`}>
        Matched as
      </h2>
      <p className={styles.matchTitle}>
        {item.title}
        {item.year ? ` (${item.year})` : ''}
        {aiAssisted && <span className={styles.aiTag}>AI-assisted</span>}
      </p>
      {item.match_confidence !== null && <Meter value={item.match_confidence} />}
      {item.match_evidence.length > 0 && (
        <>
          <h3 className={styles.subhead}>How flux decided</h3>
          <ul className={styles.evidence}>
            {item.match_evidence.map((e) => (
              <li key={e} data-ai={/\bAI\b/.test(e) || undefined}>
                {e}
              </li>
            ))}
          </ul>
        </>
      )}
      {item.external_ids.length > 0 && (
        <p className={styles.ids}>
          {item.external_ids.map(([provider, id]) => {
            const href = PROVIDER_LINKS[provider]?.(id, item.kind);
            const label = `${PROVIDER_NAMES[provider] ?? provider} ${id}`;
            return href ? (
              <a key={provider} href={href} target="_blank" rel="noreferrer noopener" className={styles.idLink}>
                {label} <Icon name="link" />
              </a>
            ) : (
              <span key={provider} className={styles.idLink}>
                {label}
              </span>
            );
          })}
        </p>
      )}
      {credits.length > 0 && (
        <ul className={styles.credits}>
          {credits.map((c) => (
            <li key={c}>{c}</li>
          ))}
        </ul>
      )}
      {usesTmdb && <p className={styles.attribution}>Metadata from TMDB. flux is not endorsed or certified by TMDB.</p>}
      <button type="button" className="btn btn-sm" disabled title="Not in this prototype yet">
        Fix match…
      </button>
    </section>
  );
}

